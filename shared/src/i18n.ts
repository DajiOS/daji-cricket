export type UiKey = keyof typeof LINES;
export const UI_KEYS = Object.keys(LINES) as UiKey[];

/** Every line for one language, key by key. */
export function uiStrings(lang: UiLang): Record<UiKey, string> {
  const i = UI_LANGUAGES.indexOf(lang);
  return Object.fromEntries(UI_KEYS.map((k) => [k, LINES[k][i]])) as Record<UiKey, string>;
}

/** One line in one language, with {placeholders} filled in. An unknown language falls back to English. */
export function uiText(lang: string | null | undefined, key: UiKey, vars: Record<string, string | number> = {}): string {
  const line = LINES[key][Math.max(0, UI_LANGUAGES.indexOf((isUiLang(lang) ? lang : 'en')))];
  return line.replace(/\{(\w+)\}/g, (m, v: string) => (v in vars ? String(vars[v]) : m));
}
