// Native side of the voice shortcuts (src/voice.ts), from voice-actions.json, for the app being built (customer or admin):
//  iOS      App Intents + App Shortcuts compiled into the app target: registered with Siri when the app is installed, each phrase with
//           the app's own name (Apple's rule). Every intent only opens the app at <scheme>://voice/<action>; it never answers on its own,
//           so Siri reads nothing out, and it needs the phone unlocked. NSUserActivityTypes lets Add to Siri (modules/daji-voice) work.
//  Android  App shortcuts (long-press the icon), bound to OPEN_APP_FEATURE so the phone's assistant can open them by voice.
const fs = require('fs');
const path = require('path');
// loaded when the plugin runs, so the generators below can be tested without the app's packages installed
const plugins = () => require('expo/config-plugins');

const ACTIONS = require('../voice-actions.json');
const SWIFT_FILE = 'DajiVoiceIntents.swift';
const swiftString = (s) => JSON.stringify(String(s)); // a Swift string literal: same escaping as JSON for this text
const xml = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, "\\'");
const typeName = (id) => `DajiVoice${id.charAt(0).toUpperCase()}${id.slice(1)}Intent`;
const actionsFor = (config) => ((config.extra && config.extra.variant) === 'admin' ? ACTIONS.staff : ACTIONS.customer);

function swiftSource(config) {
  const actions = actionsFor(config);
  const intent = (a) => {
    const param = a.screen === 'ask' ? { name: 'question', title: 'Question', ask: 'What would you like to ask?', key: 'q' } : a.screen === 'tasks' ? { name: 'taskTitle', title: 'Task', ask: 'What is the task?', key: 'title' } : null;
    return `
@available(iOS 16.0, *)
struct ${typeName(a.id)}: AppIntent {
  static var title: LocalizedStringResource = ${swiftString(a.title)}
  static var description = IntentDescription(${swiftString(`Opens ${config.name}: ${a.title}. Anything it shows stays on the screen; nothing is read out.`)})
  static var openAppWhenRun: Bool = true
  static var authenticationPolicy: IntentAuthenticationPolicy = .requiresAuthentication
${param ? `  @Parameter(title: ${swiftString(param.title)}, requestValueDialog: IntentDialog(${swiftString(param.ask)}))\n  var ${param.name}: String\n` : ''}
  @MainActor
  func perform() async throws -> some IntentResult {
    DajiVoiceLink.open(${swiftString(a.id)}${param ? `, ${swiftString(param.key)}, ${param.name}` : ''})
    return .result()
  }
}`;
  };
  const shortcut = (a) => `    AppShortcut(intent: ${typeName(a.id)}(), phrases: [${swiftString(a.phrase).replace('APP', '\\(.applicationName)')}])`;
  return `// Generated by plugins/withDajiVoice.js from voice-actions.json at build time. Do not edit by hand.
import AppIntents
import UIKit

enum DajiVoiceLink {
  /// Opens this app at its own voice link; the app's screens take it from there with the person's normal sign-in.
  @MainActor
  static func open(_ action: String, _ key: String? = nil, _ value: String? = nil) {
    var s = ${swiftString(`${config.scheme}://voice/`)} + action
    if let key = key, let value = value, let v = value.addingPercentEncoding(withAllowedCharacters: .alphanumerics) { s += "?\\(key)=\\(v)" }
    if let url = URL(string: s) { UIApplication.shared.open(url) }
  }
}
${actions.map(intent).join('\n')}

@available(iOS 16.0, *)
struct DajiVoiceShortcuts: AppShortcutsProvider {
  static var appShortcuts: [AppShortcut] {
${actions.map(shortcut).join('\n')}
  }
}
`;
}

function withIos(config) {
  const { withDangerousMod, withInfoPlist, withXcodeProject, IOSConfig } = plugins();
  config = withInfoPlist(config, (c) => {
    const type = `${c.ios.bundleIdentifier}.voice`;
    const list = Array.isArray(c.modResults.NSUserActivityTypes) ? c.modResults.NSUserActivityTypes : [];
    if (!list.includes(type)) list.push(type);
    c.modResults.NSUserActivityTypes = list;
    return c;
  });
  config = withDangerousMod(config, ['ios', async (c) => {
    const name = IOSConfig.XcodeUtils.getProjectName(c.modRequest.projectRoot);
    fs.writeFileSync(path.join(c.modRequest.platformProjectRoot, name, SWIFT_FILE), swiftSource(c));
    return c;
  }]);
  config = withXcodeProject(config, (c) => {
    const name = IOSConfig.XcodeUtils.getProjectName(c.modRequest.projectRoot);
    const file = `${name}/${SWIFT_FILE}`;
    if (!c.modResults.hasFile(file)) IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath: file, groupName: name, project: c.modResults });
    return c;
  });
  return config;
}

function shortcutsXml(config) {
  const pkg = config.android.package;
  const target = `android:targetPackage="${pkg}" android:targetClass="${pkg}.MainActivity"`;
  const actions = actionsFor(config);
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withDajiVoice.js from voice-actions.json. Each shortcut only opens the app at ${config.scheme}://voice/<action>. -->
<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">
  <capability android:name="actions.intent.OPEN_APP_FEATURE">
    <intent android:action="android.intent.action.VIEW" ${target}>
      <url-template android:value="${config.scheme}://voice/{feature}" />
      <parameter android:name="feature" android:key="feature" />
    </intent>
  </capability>
${actions.slice(0, 4).map((a) => `  <shortcut android:shortcutId="${a.id}" android:enabled="true" android:icon="@mipmap/ic_launcher" android:shortcutShortLabel="@string/daji_voice_${a.id}">
    <intent android:action="android.intent.action.VIEW" ${target} android:data="${config.scheme}://voice/${a.id}" />
    <capability-binding android:key="actions.intent.OPEN_APP_FEATURE">
      <parameter-binding android:key="feature" android:value="@string/daji_voice_${a.id}" />
    </capability-binding>
  </shortcut>`).join('\n')}
</shortcuts>
`;
}

function withAndroid(config) {
  const { withDangerousMod, withAndroidManifest, AndroidConfig } = plugins();
  config = withDangerousMod(config, ['android', async (c) => {
    const res = path.join(c.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');
    fs.mkdirSync(path.join(res, 'xml'), { recursive: true });
    fs.mkdirSync(path.join(res, 'values'), { recursive: true });
    fs.writeFileSync(path.join(res, 'xml', 'daji_voice_shortcuts.xml'), shortcutsXml(c));
    // short labels at most 25 characters, as Android asks
    const strings = actionsFor(c).map((a) => `  <string name="daji_voice_${a.id}">${xml(a.title.slice(0, 25))}</string>`).join('\n');
    fs.writeFileSync(path.join(res, 'values', 'daji_voice_strings.xml'), `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n${strings}\n</resources>\n`);
    return c;
  }]);
  config = withAndroidManifest(config, (c) => {
    const main = AndroidConfig.Manifest.getMainActivityOrThrow(c.modResults);
    main['meta-data'] = (main['meta-data'] || []).filter((m) => m.$['android:name'] !== 'android.app.shortcuts');
    main['meta-data'].push({ $: { 'android:name': 'android.app.shortcuts', 'android:resource': '@xml/daji_voice_shortcuts' } });
    return c;
  });
  return config;
}

module.exports = (config) => withAndroid(withIos(config));
module.exports.swiftSource = swiftSource;
module.exports.shortcutsXml = shortcutsXml;
